//! download the optional cleanup model (a fine tuned qwen2.5-0.5b lora,
//! exported to fp32 onnx) from huggingface.
//!
//! the cleanup model polishes raw asr output (removes fillers, fixes
//! punctuation and casing) without paraphrasing. it is opt in: the bytes are
//! only fetched when the user asks, and inference is wired in a later
//! iteration. this module owns the asset set, the on disk directory, and the
//! pre download disk space check. streaming, verification, and progress are
//! shared with parakeet via `download.rs`.
//!
//! only the fp32 onnx is shipped. dynamic int8 was measured to collapse the
//! model (punctuation f1 0.571 -> 0.171), see models/cleanup/docs/model_report.md.

