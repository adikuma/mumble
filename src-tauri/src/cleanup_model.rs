pub fn model_is_present(dir: &Path) -> bool {
    download::assets_present(dir, ASSETS)
}

pub async fn ensure_model(app: &AppHandle, dir: std::path::PathBuf, cancel: CancelFlag) -> Result<()> {
    if model_is_present(&dir) {
        return Ok(());
    }
    download::download_assets(
        app,
        &dir,
        ASSETS,
        "mumble://cleanup-download-progress",
        TOTAL_BYTES,
        Some(cancel),
    )
    .await
}

pub fn delete_model(dir: &Path) -> Result<()> {
    download::delete_assets(dir, ASSETS)
}

/// free bytes available on the volume that holds `dir`. used to gate the
/// download so a user with a near full disk is warned before 2 gb starts
/// streaming. on non windows dev hosts this returns `u64::MAX` so the check
/// never blocks frontend only smoke tests.
pub fn available_disk_bytes(dir: &Path) -> u64 {
    available_disk_bytes_impl(dir)
}

#[cfg(windows)]
fn available_disk_bytes_impl(dir: &Path) -> u64 {
    use windows::core::HSTRING;
    use windows::Win32::Storage::FileSystem::GetDiskFreeSpaceExW;

    // GetDiskFreeSpaceExW wants a directory that exists. walk up to the first
    // existing ancestor (the models dir may not be created yet).
    let mut probe = dir;
    while !probe.exists() {
        match probe.parent() {
            Some(parent) => probe = parent,
            None => return u64::MAX,
        }
    }

    let wide = HSTRING::from(probe.as_os_str());
    let mut free_available: u64 = 0;
    let ok = unsafe {
        GetDiskFreeSpaceExW(&wide, Some(&mut free_available), None, None)
    };
    match ok {
        Ok(()) => free_available,
        Err(e) => {
            tracing::warn!(?e, "GetDiskFreeSpaceExW failed, not blocking download");
            u64::MAX
        }
    }
}

#[cfg(not(windows))]
fn available_disk_bytes_impl(_dir: &Path) -> u64 {
    u64::MAX
}
